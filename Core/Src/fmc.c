/* Mode register de la SDRAM IS42S16400J segons la configuracio de referencia
 * de la STM32F429I-DISCO. Burst Length = 2, Burst Type = Sequential, CAS = 3,
 * Operating Mode = Standard, Write Burst Mode = Single. */
#define SDRAM_MODEREG  ((uint16_t)(0x0001 | (0u<<3) | (3u<<4) | (0u<<7) | (1u<<9)))

/* Refresh rate per a SDCLK = 90 MHz i refresh interval = 15.625 us
 * (4096 files / 64 ms). Comptador = 15.625e-6 * 90e6 - 20 = 1386. */
#define SDRAM_REFRESH_COUNT  ((uint32_t)1386)

/* Envia la sequencia de power-on del datasheet del IS42S16400J:
 * clock enable, delay >= 100 us, precharge all, 8 auto-refresh,
 * load mode register, i programa el refresh rate. */
static void SDRAM_Initialization_Sequence(SDRAM_HandleTypeDef *hsdram) {
    FMC_SDRAM_CommandTypeDef cmd = {0};

    /* Pas 1: Clock Configuration Enable. */
    cmd.CommandMode            = FMC_SDRAM_CMD_CLK_ENABLE;
    cmd.CommandTarget          = FMC_SDRAM_CMD_TARGET_BANK2;
    cmd.AutoRefreshNumber      = 1;
    cmd.ModeRegisterDefinition = 0;
    (void)HAL_SDRAM_SendCommand(hsdram, &cmd, 0x1000);

    /* Pas 2: delay mes gran que 100 us (1 ms es de sobres). */
    HAL_Delay(1);

    /* Pas 3: Precharge All. */
    cmd.CommandMode = FMC_SDRAM_CMD_PALL;
    (void)HAL_SDRAM_SendCommand(hsdram, &cmd, 0x1000);

    /* Pas 4: 8 cicles d'Auto-Refresh. */
    cmd.CommandMode       = FMC_SDRAM_CMD_AUTOREFRESH_MODE;
    cmd.AutoRefreshNumber = 8;
    (void)HAL_SDRAM_SendCommand(hsdram, &cmd, 0x1000);

    /* Pas 5: Load Mode Register. */
    cmd.CommandMode            = FMC_SDRAM_CMD_LOAD_MODE;
    cmd.AutoRefreshNumber      = 1;
    cmd.ModeRegisterDefinition = SDRAM_MODEREG;
    (void)HAL_SDRAM_SendCommand(hsdram, &cmd, 0x1000);

    /* Pas 6: programa el refresh rate. */
    (void)HAL_SDRAM_ProgramRefreshRate(hsdram, SDRAM_REFRESH_COUNT);
}

